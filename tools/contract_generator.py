#!/usr/bin/env python3

"""
SECBrain Watcher

Contract Generator v4

Safety Layer:

- R11 Boundary Contracts
- R12 Architecture Contracts
- R13 Application Contracts

Protection:

- no overwrite
- namespace collision detection
- existing class detection
- dry run support
"""


import sys
import subprocess
import ast
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent

CORE = ROOT / "app" / "core"


CONTRACTS = [

    "reference_contract",
    "isolation_contract",
    "provenance_contract",
    "consistency_contract",
    "integrity_regression",

]



def run_pytest():

    result = subprocess.run(
        [
            "pytest",
            "-q"
        ],
        cwd=ROOT
    )


    if result.returncode != 0:

        raise SystemExit(
            "Regression fehlgeschlagen"
        )



def existing_file_guard(target):

    if target.exists():

        raise SystemExit(
            f"""
COLLISION DETECTED

File already exists:

{target}

Generator v4 refuses overwrite.
"""
        )



def extract_classes(path):

    classes = []


    try:

        tree = ast.parse(
            path.read_text(
                encoding="utf-8"
            )
        )


        for node in ast.walk(tree):

            if isinstance(
                node,
                ast.ClassDef
            ):

                classes.append(
                    node.name
                )


    except Exception:

        pass


    return classes



def class_collision_check(target):

    if not target.exists():

        return


    classes = extract_classes(
        target
    )


    if classes:

        raise SystemExit(
            f"""
CLASS COLLISION

Existing classes:

{classes}

Target:

{target}
"""
        )



def create_safe_file(
    name,
    content,
    dry_run=False
):

    target = CORE / name


    if dry_run:

        print(
            f"[DRY RUN] would create {target}"
        )

        return


    existing_file_guard(
        target
    )


    target.write_text(
        content,
        encoding="utf-8"
    )


    print(
        f"✓ created {name}"
    )



def create_r13_layer(
    layer,
    dry_run=False
):


    for contract in CONTRACTS:


        filename = (
            f"r13_{layer}_{contract}_test.py"
        )


        class_name = (
            f"R13{layer.capitalize()}Contract"
        )


        content = f'''
"""
SECBrain Watcher

Generated by Contract Generator v4

Layer:

{layer}

Contract:

{contract}

"""



class {class_name}:


    def __init__(
        self,
        reference
    ):

        self.reference = reference



def test_contract():

    source = object()

    item = {class_name}(
        source
    )

    assert item.reference is source

'''


        create_safe_file(
            filename,
            content,
            dry_run
        )



def main():

    dry_run = (
        "--dry-run"
        in sys.argv
    )


    if len(sys.argv) < 3:

        print(
            "Usage:"
        )

        print(
            "python contract_generator.py --mode r13 layer"
        )

        print(
            "--dry-run optional"
        )

        sys.exit(1)



    mode = sys.argv[2]


    if mode == "r13":


        layer = sys.argv[3]


        print("="*70)
        print(
            "CONTRACT GENERATOR v4"
        )
        print("="*70)


        create_r13_layer(
            layer,
            dry_run
        )


        if not dry_run:

            run_pytest()


        print(
            "✓ GENERATION COMPLETE"
        )

        return



    raise SystemExit(
        "Unsupported mode"
    )



if __name__ == "__main__":

    main()
